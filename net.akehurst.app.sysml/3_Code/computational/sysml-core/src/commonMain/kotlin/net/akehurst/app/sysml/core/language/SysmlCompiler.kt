/**
 * Compiles the [CstNode] tree of SysML v2 text into the SysML v2.0 metamodel generated by net.akehurst.omg. [REQ-6.4]
 *
 * First cut, it creates:
 *  - packages, definitions and usages, owned through (Feature/Owning)Memberships,
 *  - comments and documentation,
 *  - feature typing, subclassification, subsetting, redefinition and reference subsetting relationships,
 *  - connection ends, and the subject of satisfy requirement usages.
 * Expressions and behaviour (actions nodes, transitions) are not yet compiled.
 * References are by name ([Reference.reference] is the text) and are resolved by [resolveReferences].
 */
class SysmlCompiler(val factory: SysML_ModelFactory) {

    /** the metaclass (by name) that each compiled element was created as */
    val metaclassOf = mutableMapOf<Element, String>()

    /** the file each element is declared in */
    val fileOf = mutableMapOf<Element, String>()

    /** the root namespace for each compiled file */
    val roots = linkedMapOf<String, Namespace>()

    private class Pending(val scope: Element, val relationship: Element, val ref: Reference<Any, *>, val text: String)

    private val pending = mutableListOf<Pending>()
    private var nextId = 0
    private lateinit var file: String

    private fun id(kind: String) = "$file#$kind#${nextId++}"

    fun compile(file: String, root: CstNode): Namespace {
        this.file = file
        val ns = factory.KerML.Root.Namespaces.Namespace_construct(id("Namespace"))
        metaclassOf[ns] = "Namespace"
        fileOf[ns] = file
        roots[file] = ns
        members(ns, root)
        return ns
    }

    // --- elements ---

