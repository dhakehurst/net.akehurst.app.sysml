    /** compiles the element nodes found below [node] (not inside other elements) as members of [owner] */
    private fun members(owner: Element, node: CstNode) {
        for (en in elementNodes(node)) {
            val el = element(en)
            own(owner, el)
            if (el is Documentation) el.documentedElementReference.mutable.set(owner._identity, owner)
        }
    }

    private fun elementNodes(node: CstNode): List<CstNode> {
        val result = mutableListOf<CstNode>()
        fun walk(n: CstNode) {
            for (c in n.children) if (isElementNode(c)) result += c else walk(c)
        }
        walk(node)
        return result
    }

    private fun own(owner: Element, el: Element) {
        val membership: OwningMembership = if (owner is Type && el is Feature) {
            factory.KerML.Core.Types.FeatureMembership_construct(id("FeatureMembership")).also { it.ownedMemberFeatureValue.mutable.set(el) }
        } else {
            factory.KerML.Root.Namespaces.OwningMembership_construct(id("OwningMembership"))
        }
        membership.ownedMemberElementValue.mutable.set(el)
        el.name?.let { membership.ownedMemberNameValue.mutable.set(it) }
        membership.ownedRelatedElementOrderedSet.mutable.add(el)
        owner.ownedRelationshipOrderedSet.mutable.add(membership)
    }

    private fun element(n: CstNode): Element {
        val metaclass = elementRules[n.rule]!!
        val el = construct(metaclass)
        // the declaration part of the node, i.e. not inside a nested element
        val stop = isElementNode
        n.find("Identification", stop)?.let { identification(el, it) }
        when (el) {
            is Comment -> n.find("REGULAR_COMMENT", stop)?.let { el.bodyValue.mutable.set(commentBody(it.text!!)) }
            else -> {}
        }
        // relationships declared in the element's declaration (not in connector ends, the subject of a satisfy, or values)
        val declaration: (CstNode) -> Boolean = { isElementNode(it) || it.rule in notDeclaration }
        for (t in n.findAll("FeatureTyping", declaration) + n.findAll("ConjugatedPortTyping", declaration)) {
            if (el is Feature) typing(el, t)
        }
        for (s in n.findAll("OwnedSubclassification", declaration)) {
            if (el is Classifier) subclassification(el, s)
        }
        for (s in n.findAll("OwnedSubsetting", declaration)) {
            if (el is Feature) subsetting(el, s)
        }
        for (r in n.findAll("OwnedRedefinition", declaration)) {
            if (el is Feature) redefinition(el, r)
        }
        for (r in n.findAll("OwnedReferenceSubsetting", declaration)) {
            if (el is Feature) referenceSubsetting(el, el, r)
        }
        when (el) {
            is ConnectionUsage, is FlowUsage, is BindingConnectorAsUsage, is SuccessionAsUsage, is AllocationUsage -> connectorEnds(el as Feature, n)
            is SatisfyRequirementUsage -> n.find("SatisfactionSubjectMember", stop)?.let { satisfactionSubject(el, it) }
            else -> {}
        }
        // nested members, from the body of the element
        members(el, n)
        return el
    }

    private fun identification(el: Element, n: CstNode) {
        val names = n.children("NAME")
        val shortName = if (n.children.firstOrNull()?.text == "<") names.firstOrNull() else null
        val name = names.lastOrNull()?.takeIf { it !== shortName }
        shortName?.let { el.declaredShortNameValue.mutable.set(unquote(it.leafText())) }
        name?.let {
            val nm = unquote(it.leafText())
            el.declaredNameValue.mutable.set(nm)
            el.nameValue.mutable.set(nm)
        }
        if (null == name) shortName?.let { el.nameValue.mutable.set(unquote(it.leafText())) }
    }

    // --- relationships ---

    /** the referenced name in a node: a QualifiedName or a feature chain (a.b.c) */
    private fun referenceText(n: CstNode): String? {
        val chain = n.find("OwnedFeatureChain") ?: n.find("FeatureChainPrefix")
        if (null != chain) return chain.findAll("QualifiedName").joinToString(".") { qualifiedNameText(it) }
        return n.find("QualifiedName")?.let { qualifiedNameText(it) }
    }

    private fun qualifiedNameText(n: CstNode): String = n.leafText()

    private fun typing(f: Feature, n: CstNode) {
        val name = referenceText(n) ?: return
        val r = factory.KerML.Core.Features.FeatureTyping_construct(id("FeatureTyping"))
        r.typedFeatureReference.mutable.set(f._identity, f)
        defer(f, r, r.typeReference, name)
        f.ownedRelationshipOrderedSet.mutable.add(r)
    }

    private fun subclassification(c: Classifier, n: CstNode) {
        val name = referenceText(n) ?: return
        val r = factory.KerML.Core.Classifiers.Subclassification_construct(id("Subclassification"))
        r.subclassifierReference.mutable.set(c._identity, c)
        defer(c, r, r.superclassifierReference, name)
        c.ownedRelationshipOrderedSet.mutable.add(r)
    }

    private fun subsetting(f: Feature, n: CstNode) {
        val name = referenceText(n) ?: return
        val r = factory.KerML.Core.Features.Subsetting_construct(id("Subsetting"))
        r.subsettingFeatureReference.mutable.set(f._identity, f)
        defer(f, r, r.subsettedFeatureReference, name)
        f.ownedRelationshipOrderedSet.mutable.add(r)
    }

    private fun redefinition(f: Feature, n: CstNode) {
        val name = referenceText(n) ?: return
        val r = factory.KerML.Core.Features.Redefinition_construct(id("Redefinition"))
        r.redefiningFeatureReference.mutable.set(f._identity, f)
        defer(f, r, r.redefinedFeatureReference, name)
        f.ownedRelationshipOrderedSet.mutable.add(r)
    }

    private fun referenceSubsetting(scope: Element, f: Feature, n: CstNode) {
        val name = referenceText(n) ?: return
        val r = factory.KerML.Core.Features.ReferenceSubsetting_construct(id("ReferenceSubsetting"))
        r.referencingFeatureReference.mutable.set(f._identity, f)
        defer(scope, r, r.referencedFeatureReference, name)
        f.ownedRelationshipOrderedSet.mutable.add(r)
    }

    /** each end of a connector is an end feature that references the connected feature */
    private fun connectorEnds(connector: Feature, n: CstNode) {
        val ends = n.findAll("ConnectorEnd", isElementNode) + n.findAll("FlowEnd", isElementNode)
        for (e in ends) {
            val end = construct("ReferenceUsage") as Feature
            val name = referenceText(e) ?: continue
            val r = factory.KerML.Core.Features.ReferenceSubsetting_construct(id("ReferenceSubsetting"))
            r.referencingFeatureReference.mutable.set(end._identity, end)
            // the connected features are named in the scope of the connector's owner
            defer(connector, r, r.referencedFeatureReference, name)
            end.ownedRelationshipOrderedSet.mutable.add(r)
            val m = factory.KerML.Core.Features.EndFeatureMembership_construct(id("EndFeatureMembership"))
            m.ownedMemberFeatureValue.mutable.set(end)
            m.ownedMemberElementValue.mutable.set(end)
            m.ownedRelatedElementOrderedSet.mutable.add(end)
            connector.ownedRelationshipOrderedSet.mutable.add(m)
        }
    }

    /** the subject of a satisfy is a ReferenceUsage, owned by a SubjectMembership, that references the satisfying feature */
    private fun satisfactionSubject(satisfy: SatisfyRequirementUsage, n: CstNode) {
        val name = referenceText(n) ?: return
        val subject = construct("ReferenceUsage") as ReferenceUsage
        val r = factory.KerML.Core.Features.ReferenceSubsetting_construct(id("ReferenceSubsetting"))
        r.referencingFeatureReference.mutable.set(subject._identity, subject)
        defer(satisfy, r, r.referencedFeatureReference, name)
        subject.ownedRelationshipOrderedSet.mutable.add(r)
        val m = factory.SysML.Systems.Requirements.SubjectMembership_construct(id("SubjectMembership"))
        m.ownedMemberFeatureValue.mutable.set(subject)
        m.ownedMemberElementValue.mutable.set(subject)
        m.ownedRelatedElementOrderedSet.mutable.add(subject)
        satisfy.ownedRelationshipOrderedSet.mutable.add(m)
    }

    @Suppress("UNCHECKED_CAST")
    private fun defer(scope: Element, relationship: Element, ref: Reference<Any, *>, text: String) {
        (ref as Reference<Any, Any>).mutable.set(text, null)
        pending += Pending(scope, relationship, ref, text)
    }

    /**
     * the element named by the target of each relationship created, also where it is not of the metaclass the relationship requires
     * (e.g. 'satisfy R by x' where R is a requirement definition rather than a usage)
     */
    val targetOf = mutableMapOf<Element, Element>()

    // --- name resolution ---

    /**
     * Resolves the references of all compiled files by name, see [NameResolver].
     * @return the texts of the references that could not be resolved, with the element in whose scope they are
     */
    fun resolveReferences(): List<Pair<Element, String>> {
        val resolver = NameResolver(roots.values.toList())
        var todo: List<Pending> = pending
        // a feature chain can depend on a reference later in the text (the type of its first feature), so try twice
        repeat(2) {
            todo = todo.filter { p ->
                val target = resolver.resolve(p.scope, p.text)
                target?.let { targetOf[p.relationship] = it }
                if (null == target) true else try {
                    @Suppress("UNCHECKED_CAST")
                    (p.ref as Reference<Any, Any>).mutable.set(p.text, target)
                    false
                } catch (e: Exception) {
                    // the named element is not of the type the reference requires, leave it unresolved
                    true
                }
            }
        }
        return todo.map { it.scope to it.text }
    }

    private fun unquote(s: String) = if (s.length >= 2 && s.startsWith("'") && s.endsWith("'")) s.substring(1, s.length - 1) else s

    private fun commentBody(text: String): String =
        text.removePrefix("/*").removeSuffix("*/").lines().joinToString("\n") { it.trim().removePrefix("*").trim() }.trim()
}
