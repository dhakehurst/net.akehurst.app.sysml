    private val isElementNode: (CstNode) -> Boolean = { it.rule in elementRules }

    private val notDeclaration = setOf("ConnectorEnd", "FlowEnd", "SatisfactionSubjectMember", "ValuePart", "FeatureValue", "ActionBody", "DefinitionBody")

